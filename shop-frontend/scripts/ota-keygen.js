/*
 * One-time setup for signed over-the-air updates.
 *
 *   node scripts/ota-keygen.js
 *
 * Creates the ECDSA P-256 key pair that signs every OTA bundle:
 *   - PRIVATE key → ~/.blitzmall/ota-signing-key.pem (or $OTA_SIGNING_KEY).
 *     Lives outside the repo and is never uploaded anywhere. BACK IT UP off this
 *     machine: without it no installed app will accept a new OTA bundle (they'd
 *     need a fresh APK carrying a new public key).
 *   - PUBLIC key  → src/otaPublicKey.js, compiled into the app. The app refuses
 *     any bundle whose signature doesn't verify against it, so even a hacked or
 *     impersonated server can't push code onto customers' phones.
 *
 * Refuses to overwrite an existing private key.
 */
const fs = require('fs');
const os = require('os');
const path = require('path');
const crypto = require('crypto');

const KEY_PATH = process.env.OTA_SIGNING_KEY || path.join(os.homedir(), '.blitzmall', 'ota-signing-key.pem');
const PUB_OUT = path.join(__dirname, '..', 'src', 'otaPublicKey.js');

function writePublicModule(publicKey) {
  const spki = publicKey.export({ type: 'spki', format: 'der' }).toString('base64');
  fs.writeFileSync(PUB_OUT,
    '// Generated by scripts/ota-keygen.js — do not edit.\n' +
    '// Public half of the OTA signing key: the app only installs over-the-air\n' +
    '// bundles signed by the matching private key (see src/otaUpdate.js).\n' +
    `export const OTA_PUBLIC_KEY_SPKI = '${spki}';\n`);
  console.log(`[ota-keygen] Public key written to ${path.relative(process.cwd(), PUB_OUT)}`);
}

if (fs.existsSync(KEY_PATH)) {
  // Re-derive the public module from the existing key (e.g. a fresh checkout).
  const priv = crypto.createPrivateKey(fs.readFileSync(KEY_PATH));
  writePublicModule(crypto.createPublicKey(priv));
  console.log(`[ota-keygen] Kept existing private key at ${KEY_PATH}`);
  process.exit(0);
}

const { privateKey, publicKey } = crypto.generateKeyPairSync('ec', { namedCurve: 'prime256v1' });
fs.mkdirSync(path.dirname(KEY_PATH), { recursive: true });
fs.writeFileSync(KEY_PATH, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600 });
writePublicModule(publicKey);
console.log(`[ota-keygen] Private key written to ${KEY_PATH}`);
console.log('[ota-keygen] BACK THIS FILE UP somewhere safe (password manager / USB). Losing it means');
console.log('             installed apps stop accepting OTA updates until they get a new APK.');
