/*
 * Writes src/version.generated.js from package.json so the app can show its own
 * version in Settings → About (CRA can't import files outside src/). Runs
 * automatically before every build/start (npm "pre" scripts).
 */
const fs = require('fs');
const path = require('path');
const pkg = require(path.join(__dirname, '..', 'package.json'));
const out = path.join(__dirname, '..', 'src', 'version.generated.js');
const body = `// Generated by scripts/write-version.js — do not edit.\nexport const APP_VERSION = '${pkg.version}';\n`;
if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== body) fs.writeFileSync(out, body);
